def create_full_detail_pdf(filename="Luxury_Home_Full_Details.pdf"):
    # ถ้าไม่มีฟอนต์ไทย สามารถใช้ Courier ไปก่อน
    # ถ้าคุณมีไฟล์ THSarabunNew.ttf ให้เพิ่มฟอนต์และเปลี่ยน set_font
    pdf = FPDF()
    pdf.add_page()
    
    # pdf.add_font("THSarabunNew", "", "THSarabunNew.ttf", uni=True)
    # pdf.set_font("THSarabunNew", size=14)
    
    pdf.set_font("Courier", size=10)
    
    # Multi_cell ให้ข้อความไหลขึ้นบรรทัดใหม่อัตโนมัติ
